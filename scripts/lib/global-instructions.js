"use strict";

// Renders the harness-specific global instruction files from one shared
// template so shared rules cannot drift between harnesses. Each harness overlay
// must define exactly the slots the template uses; a missing, unused, or
// misplaced slot is an error rather than a silently different output.

const fs = require("node:fs");
const path = require("node:path");

const instructionsDir = path.resolve(__dirname, "../../global-agent-instructions");
const sourceDir = path.join(instructionsDir, "src");
const templateFile = path.join(sourceDir, "template.md");

// Harness name -> generated file. Overlays live at src/overlay-<harness>.md;
// the prefix keeps Claude Code from loading an overlay as a nested CLAUDE.md on
// case-insensitive filesystems.
const harnessOutputs = new Map([
  ["claude", "global-claude.md"],
  ["codex", "global-codex.md"]
]);

const generatedNotice =
  "<!-- Generated by scripts/build-global-instructions from global-agent-instructions/src/. Edit the sources, then rebuild. -->";

const placeholderPattern = /\{\{([a-z0-9_]+)\}\}/g;
const slotMarkerPattern = /^<!-- slot: ([a-z0-9_]+) -->$/;

function normalizeNewlines(text) {
  return text.replace(/\r\n/g, "\n");
}

function trimBlankLines(lines) {
  let start = 0;
  let end = lines.length;
  while (start < end && !lines[start].trim()) start += 1;
  while (end > start && !lines[end - 1].trim()) end -= 1;
  return lines.slice(start, end);
}

function parseOverlay(content, label) {
  const errors = [];
  const slots = new Map();
  let current = null;
  let buffer = [];

  const flush = () => {
    if (current !== null) slots.set(current, trimBlankLines(buffer).join("\n"));
  };

  for (const [index, line] of normalizeNewlines(content).split("\n").entries()) {
    const marker = line.match(slotMarkerPattern);
    if (marker) {
      flush();
      current = marker[1];
      buffer = [];
      if (slots.has(current)) errors.push(`${label}:${index + 1}: duplicate slot ${current}`);
      continue;
    }
    if (current === null) {
      if (line.trim()) errors.push(`${label}:${index + 1}: content before the first slot marker`);
      continue;
    }
    buffer.push(line);
  }
  flush();

  return { slots, errors };
}

function render(template, slots, label) {
  const errors = [];
  const used = new Set();
  const lines = [];

  for (const [index, line] of normalizeNewlines(template).split("\n").entries()) {
    const standalone = line.match(/^\{\{([a-z0-9_]+)\}\}$/);
    if (standalone) {
      const name = standalone[1];
      used.add(name);
      if (!slots.has(name)) {
        errors.push(`${label}: missing slot ${name} (template line ${index + 1})`);
        continue;
      }
      if (slots.get(name)) {
        lines.push(slots.get(name));
      } else if (lines.length > 0 && !lines[lines.length - 1].trim()) {
        // Drop the removed block's leading separator so no blank run remains.
        lines.pop();
      }
      continue;
    }

    lines.push(
      line.replace(placeholderPattern, (match, name) => {
        used.add(name);
        if (!slots.has(name)) {
          errors.push(`${label}: missing slot ${name} (template line ${index + 1})`);
          return match;
        }
        const value = slots.get(name);
        if (value.includes("\n")) {
          errors.push(`${label}: multi-line slot ${name} used inline (template line ${index + 1})`);
        }
        return value;
      })
    );
  }

  for (const name of slots.keys()) {
    if (!used.has(name)) errors.push(`${label}: slot ${name} is not used by the template`);
  }

  const body = lines.join("\n").trim();
  return { output: `${generatedNotice}\n\n${body}\n`, errors };
}

function buildAll() {
  const template = fs.readFileSync(templateFile, "utf8");
  const results = [];
  for (const [harness, outputName] of harnessOutputs) {
    const overlayFile = path.join(sourceDir, `overlay-${harness}.md`);
    const label = path.relative(instructionsDir, overlayFile);
    const overlay = parseOverlay(fs.readFileSync(overlayFile, "utf8"), label);
    const rendered = render(template, overlay.slots, label);
    results.push({
      harness,
      outputFile: path.join(instructionsDir, outputName),
      output: rendered.output,
      errors: [...overlay.errors, ...rendered.errors]
    });
  }
  return results;
}

// Returns problems that make the committed generated files untrustworthy.
function checkGenerated(results = buildAll()) {
  const problems = [];
  for (const result of results) {
    problems.push(...result.errors);
    if (result.errors.length > 0) continue;
    const current = fs.existsSync(result.outputFile)
      ? normalizeNewlines(fs.readFileSync(result.outputFile, "utf8"))
      : null;
    if (current !== result.output) {
      problems.push(
        `${path.basename(result.outputFile)} is stale; run scripts/build-global-instructions`
      );
    }
  }
  return problems;
}

module.exports = {
  buildAll,
  checkGenerated,
  generatedNotice,
  parseOverlay,
  render
};
